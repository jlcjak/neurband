#!/usr/bin/env python3
"""Design the rev C streaming filters and write src/filter_coefs.h (numpy only).

  python3 tools/gen_filters.py          # from firmware_c/

Pipeline (docs/science/signal_chain.md section 4, docs/firmware_c.md "DSP"):
  ADS1298 at 4 kSPS -> slow integer DC tracker (also the raw-DC diagnostic) ->
  127-tap Kaiser FIR (beta 5.65, cutoff 925 Hz), decimate by 2 -> 4th-order Butterworth
  high-pass (20 or 40 Hz) at 2 kSPS, two float32 DF2T biquads -> 0.25 uV/count int16.
The script also checks the FIR response and the float32 rounding error of the biquads.
"""
import os

import numpy as np

FS_IN, FS_OUT = 4000.0, 2000.0
NTAPS, BETA, FC = 127, 5.65, 925.0
HP_FREQS = (20.0, 40.0)
BUTTER4_Q = (1.0 / (2 * np.cos(np.pi / 8)), 1.0 / (2 * np.cos(3 * np.pi / 8)))  # 0.5412, 1.3066


def fir_taps():
    n = np.arange(NTAPS) - (NTAPS - 1) / 2
    h = 2 * FC / FS_IN * np.sinc(2 * FC / FS_IN * n) * np.kaiser(NTAPS, BETA)
    return h / h.sum()  # unity DC gain


def response_db(b, a, f, fs):
    z = np.exp(-2j * np.pi * np.asarray(f) / fs)
    num = np.polyval(np.asarray(b)[::-1], z)
    den = np.polyval(np.asarray(a)[::-1], z)
    return 20 * np.log10(np.abs(num / den))


def hp_biquad(f0, q, fs):
    """RBJ cookbook high-pass = bilinear transform with prewarping. Returns b, a (a0 = 1)."""
    w0 = 2 * np.pi * f0 / fs
    al = np.sin(w0) / (2 * q)
    c = np.cos(w0)
    b = np.array([(1 + c) / 2, -(1 + c), (1 + c) / 2])
    a = np.array([1 + al, -2 * c, 1 - al])
    return b / a[0], a / a[0]


def df2t_f32(x, sections):
    """Bit-faithful float32 model of the firmware's dsp.c biquad cascade."""
    f = np.float32
    y = np.empty(len(x), np.float32)
    st = [[f(0), f(0)] for _ in sections]
    for i, v in enumerate(x.astype(np.float32)):
        for (b, a), s in zip(sections, st):
            o = f(f(b[0]) * v + s[0])
            s[0] = f(f(b[1]) * v - f(a[1]) * o + s[1])
            s[1] = f(f(b[2]) * v - f(a[2]) * o)
            v = o
        y[i] = v
    return y


def df2t_f64(x, sections):
    y = np.asarray(x, np.float64).copy()
    for b, a in sections:
        s1 = s2 = 0.0
        out = np.empty_like(y)
        for i, v in enumerate(y):
            o = b[0] * v + s1
            s1 = b[1] * v - a[1] * o + s2
            s2 = b[2] * v - a[2] * o
            out[i] = o
        y = out
    return y


def main():
    h = fir_taps()
    f_pass = np.linspace(0, 850, 400)
    f_stop = np.linspace(1000, 2000, 400)
    pb = response_db(h, [1.0], f_pass, FS_IN)
    sb = response_db(h, [1.0], f_stop, FS_IN)
    print(f"FIR {NTAPS} taps: passband 0-850 Hz error {np.max(np.abs(pb)):.4f} dB, "
          f"stopband >=1 kHz {-np.max(sb):.1f} dB, delay {(NTAPS - 1) / 2 / FS_IN * 1e3:.2f} ms")
    assert np.max(np.abs(pb)) < 0.01 and -np.max(sb) > 62
    assert np.allclose(h, h[::-1])

    lines = ["/* Generated by tools/gen_filters.py - do not edit. */", "#pragma once", "",
             f"#define FIR_TAPS {NTAPS} /* Kaiser beta {BETA}, cutoff {FC:.0f} Hz at {FS_IN:.0f} SPS, "
             "unity DC gain, symmetric */",
             "static const float fir_taps[FIR_TAPS] = {"]
    for i in range(0, NTAPS, 4):
        lines.append("\t" + " ".join(f"{v: .9e}f," for v in h[i:i + 4]))
    lines += ["};", "", "/* 4th-order Butterworth high-pass at 2000 SPS: two DF2T biquads {b0,b1,b2,a1,a2} */",
              "static const float hp_coefs[][2][5] = {"]
    rng = np.random.default_rng(1)
    t = np.arange(int(4 * FS_OUT)) / FS_OUT
    # residual after the DC tracker: drift of +-2 mV, 50 Hz 20 uV, broadband EMG ~200 uV rms, in codes
    lsb = 2 * 2.4 / 6 / 2 ** 24
    x = (2e-3 * np.sin(2 * np.pi * 0.3 * t) + 20e-6 * np.sin(2 * np.pi * 50 * t)
         + 200e-6 * rng.standard_normal(len(t))) / lsb
    for f0 in HP_FREQS:
        secs = [hp_biquad(f0, q, FS_OUT) for q in BUTTER4_Q]
        b = np.convolve(secs[0][0], secs[1][0])
        a = np.convolve(secs[0][1], secs[1][1])
        g = response_db(b, a, [f0, 2 * f0, 100.0, 450.0, 850.0], FS_OUT)
        err = (df2t_f32(x, secs) - df2t_f64(x, secs))[len(t) // 4:] * lsb * 1e6
        print(f"HP {f0:.0f} Hz: gain at f0/2f0/100/450/850 Hz = " + "/".join(f"{v:.2f}" for v in g)
              + f" dB; float32 rounding error {np.sqrt(np.mean(err ** 2)) * 1e3:.2f} nV rms")
        assert abs(g[0] + 3.01) < 0.05 and np.sqrt(np.mean(err ** 2)) < 0.02  # < 20 nV
        lines.append(f"\t{{ /* {f0:.0f} Hz */")
        for bb, aa in secs:
            lines.append("\t\t{" + ", ".join(f"{v: .9e}f" for v in (*bb, aa[1], aa[2])) + "},")
        lines.append("\t},")
    lines += ["};", f"static const unsigned short hp_freqs[] = {{{', '.join(str(int(f)) for f in HP_FREQS)}}};", ""]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "filter_coefs.h")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
